package com.BasesDeDatos.demo.dto;

public class PreMatriculaDTO {
    private String periodo;
    private String asigCodigo;
    private String asigNombre;

    // Getters y Setters
    public String getPeriodo() { return periodo; }
    public void setPeriodo(String periodo) { this.periodo = periodo; }

    public String getAsigCodigo() { return asigCodigo; }
    public void setAsigCodigo(String asigCodigo) { this.asigCodigo = asigCodigo; }

    public String getAsigNombre() { return asigNombre; }
    public void setAsigNombre(String asigNombre) { this.asigNombre = asigNombre; }
}